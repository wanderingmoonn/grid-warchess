/**
 * 战略层：给 AI 一个"远期规划"的口子，战术层一行不改。
 *
 * ── 为什么要单独一层 ────────────────────────────────────────────
 *
 * 现有 AI 是"每回合对每个候选打分取最大"。这套东西做局部操作很好（走位、
 * 集火、造什么），但没有任何地方能表达"我现在该发展还是该打"——
 * 实测：12×12 上它 60 回合还停在 2 代，对面 3 代，因为钱全变成兵了。
 *
 * 目标状态机（`ai-goal.ts`）解决了"跨回合的投资"，但"什么时候开打"仍然
 * 散落在 `stance` / `mood` 里。这一层就是补上那个缺失的判断。
 *
 * ── 为什么是回调，不是重写 ──────────────────────────────────────
 *
 * 战术层（走位评分、集火、采购排序）是这三年攒下来的，重写等于扔掉它。
 * 所以战略层只回答**三个问题**，回答完就退场：
 *
 *   · `mayAttack`  —— 现在能不能主动进攻（不能就压掉攻城/过河推进）
 *   · `econShare`  —— 每回合的名额里，多少比例留给经济单位
 *   · `desiredEra` —— 这一局我想打到第几代（决战时代）
 *
 * 传 `null` 就是现在的行为（三个问题都按老逻辑答），所以**老 AI 完全不受影响**，
 * 新算法只是换一个实现挂上去。这样才敢做实验。
 */

/** 战略层要回答的三件事 */
export interface Strategist {
  /** 现在能不能主动进攻。false = 压掉攻城与"朝敌城推进"的走位 */
  mayAttack(s: unknown, me: string): boolean;
  /** 每回合名额里留给经济的比例（0~1）。1 = 全投经济，0 = 全投兵 */
  econShare(s: unknown, me: string): number;
  /** 决战时代：这一局打算打到第几代（1~9） */
  desiredEra(s: unknown, me: string): number;
}

/**
 * 空战略层：三个问题都按"老逻辑"答。
 *
 * `mayAttack` 恒 true、`desiredEra` 恒 0（= 不表态）、`econShare` 恒 -1
 * （= 不干预）。挂它等于没挂，用来验证"这个口子本身不改变行为"。
 */
export const NULL_STRATEGIST: Strategist = {
  mayAttack: () => true,
  econShare: () => -1,
  desiredEra: () => 0,
};
