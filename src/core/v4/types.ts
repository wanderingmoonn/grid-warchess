/**
 * v4 三层的**数据契约**。
 *
 * 这个文件里没有算法，只有"每层准输出什么"。它是 v4 和 v3 最大的区别：
 * v3 的三层都可以往同一张分数表里加一项，所以谁也说不清一个决定是谁做的；
 * v4 的三层各自只能交出下面这几种东西，越界的形状根本编译不过。
 *
 * ```
 *   决定层  decide.ts    ──→  Decision（做什么 + 期限 + 理由）
 *                              ↓
 *   约束层  constrain.ts ──→  Constraints（哪几格必须空、哪几个兵归哪队、去打哪座城）
 *                              ↓
 *   打分层  tactics.ts   ──→  Action（引擎认的那一个动作）
 * ```
 */

/** 决定层能做的三种事。**只有这三种**，想加第四种先证明前三种表达不了它 */
export type DecisionKind = 'expand' | 'press' | 'defend' | 'takeover';

/**
 * 接管废墟的三个子阶段。**顺序是硬的**：先清场，再攒钱，最后入驻。
 *
 *   · `clear`：废墟周围还有能威胁它的敌人 → 先打，不攒钱（该花就花）；
 *   · `save`：干净了，但钱不够重建费 → 停止造兵，等金币攒够；
 *   · `enter`：钱够了 → 派一个兵走进废墟。
 *
 * 为什么分三段而不是"一个接管分"：三段做的事完全不同（打仗 / 不花钱 / 走一格），
 * 混成一个数就又会变成"该打还是该攒"的调参表。
 */
export type TakeoverStage = 'clear' | 'save' | 'enter';

/**
 * `press` 的两个阶段。
 *
 * **先清场、再砸城**：城周围的守军还在时全队打人，清到"威胁不到我方"才开始攻城。
 * 这条是从 S-002 的人手答案里量出来的——人类第 3/5/7/9 手一次攻城都没有（25 次攻击全是打人），
 * 第 11 手才第一次 `SIEGE`。
 */
export type PressStage = 'clear' | 'siege';

export interface Decision {
  kind: DecisionKind;
  /** `takeover` 用 `TakeoverStage`，`press` 用 `PressStage` */
  stage?: TakeoverStage | PressStage;
  /** 这个决定管到第几手为止。到了就重算——**不许"一直有效"**，那样它会悄悄变成常数 */
  untilTurn: number;
  /** 一句话说明为什么（进日志，出问题时第一眼看这个） */
  reason: string;
  /** press / defend 指向哪座城（`expand` 没有目标城） */
  cityId?: string;
}

/** 一支部队在本回合的任务。**任务种类固定**，别用"分数"表达意图 */
export type SquadOrder =
  /** 开到集结点（不接敌） */
  | 'assemble'
  /** 向目标城推进，路上遇敌就打 */
  | 'march'
  /** 贴着目标城打（优先攻城/清守军） */
  | 'siege'
  /** 守在原地/守城（不主动出击） */
  | 'hold'
  /**
   * **让开**（2026-11-25）：站在"这一手必须空"的格子上，这一手的任务就是把那格腾出来。
   *
   * 为什么要给它们一个任务名：以前这些兵被**摘出所有队伍**——不是"任务是比较开"，
   * 而是"没有任务"，于是不报错、不复盘、日志里看不见（回放里表现为"它突然不动了"）。
   * 现在它们照旧不在主队里（这一手确实不能跟着走），但**有一个说得出的任务**。
   *
   * **2026-11-25 加（清 9.18）：这个任务现在带方向。** 见 `Constraints.transit`。
   */
  | 'yield';

export interface Squad {
  id: string;
  order: SquadOrder;
  unitIds: string[];
  /** assemble 的集结点 */
  at?: { x: number; y: number };
  /** march / siege 的目标城 */
  cityId?: string;
  /** 目标人数：按目标城守军算，成立时定下，之后不因伤亡而缩（见 V4Memory.squad） */
  want?: number;
  /**
   * 采购的**门槛**（约束）：要造什么样的兵。挂在约束层（不是某支队）——
   * 守城时同样要按对面的构成配兵，而守城时根本没有 `main` 队。
   *
   * 两条不等式，都从"目标城的守军"算出来，不是偏好、不是权重：
   *   · `hp`：能挨住对面一发（`hp > 敌方单发攻击`）——挨不住就等于白送；
   *   · `atk`：能在三发内打穿（`atk × 3 ≥ 敌方血量`）——打不穿等于没来。
   * 满足这两条的里面**先挑射程远的**（先手权），射程一样才看价钱。
   * （这里原来写的是"挑最便宜的"——那是错的，代码从来没这么做过，见 8.15。）
   */
  /** 分路：本队拆成几条走廊（路数由地形宽度决定，见 constrain.planLanes） */
  lanes?: Array<{ x: number; y: number }>;
  /** 每个单位走第几条路 */
  laneOf?: Record<string, number>;
  /** 这一队要不要寻路绕（目标直线走不通，比如隔着河）：整队一个判断，不按单个兵 */
  detour?: boolean;
  /** 全队最慢的人赶到目标还要几回合（Infinity = 到不了）。出发条件读它 */
  eta?: number;
  /**
   * **战术模式**（2026-11-25 加）：这一手准不准打分层"多做一点"。
   *
   * 为什么要有这个开关：v1/v3 的毛病不是"会打分"，而是**任何情况下都在打分**——
   * 每一步都在比较落点，于是队形永远形不成、意图永远被一个数盖住。
   * 所以打分层默认只做两件事：**照约束执行、打射程内的**。
   * 只有当约束层判定"这一手有一个值得全队一起办的目标"时，才把 `tactics` 挂上，
   * 解锁集火/靠拢这类动作；没挂 = 行为与原来一字不差。
   *
   * 不同队伍开这个开关的条件不同（见 `constrain.planTactics`）：
   * 进攻队可以"走一步再打"算进伤害，守队只算当下够得着的，所以守队更难开。
   */
  tactics?: SquadTactics;
}

/**
 * 一支队伍这一手的**战术模式**。
 *
 * 只有一件事被授权：**全队打同一个目标**（`focusId`），以及为它挪一步（`converge`）。
 * 别的（撤退、让位、造兵）都不在这里——那些是约束层的任务，不是战术动作。
 */
export interface SquadTactics {
  /** 全队这一手打同一个。为什么必须"全队一个"：逐兵各自最优必然摊平（X-1-01 实测） */
  focusId: string;
  /** 允许为了打到它挪一步。守队、攻城队不开——一个不许离开城，一个目标是城 */
  converge: boolean;
  /** 进战术模式的一句人话（进回放，出问题第一眼看它） */
  why: string;
}

/**
 * 约束层交出来的东西。
 *
 * `keepClear` 是这一层的**核心**：v3 折腾三轮"让位"失败，根因是它想用分数表达"必须"。
 * 在 v4 里"这几格必须空"是一个约束，打分层只许照做，不许权衡。
 */
export interface Constraints {
  /**
   * **经济兵的岗位**（约束层）：每个经济兵该站哪一格。
   *
   * 为什么必须在这一层："去森林"原来只是打分层每步重算的结果，
   * 一旦被"让开产兵格"推走，它就没有终点可回——实测伐木工被推到北边平原，
   * 下一手就再也回不到两格外的森林（S-015 卡在 19 的原因）。
   *
   * 有了岗位，两个约束不再打架：**让位是绕路，岗位是终点。**
   */
  econPosts?: Record<string, { x: number; y: number }>;
  /**
   * **下一个该造的经济兵**（约束层）：认领表里还没人认领、且"到这个决定结束前
   * 能赚回的倍数"最高的那一格。造兵只照这个执行，不再自己比价、比产出。
   *
   * 没有它 = 表里没有值得占的格（或者钱/出兵格不够），这回合就别造经济兵。
   */
  econNext?: { type: string; x: number; y: number };
  /**
   * **经济兵这一手的行动顺序**（约束层）：靠自己岗位近的排在前面。
   *
   * 为什么顺序也是约束：人挤人时，"谁先动"决定整列能不能往前挪——
   * 前面的人先走开，后面的人才看得到空格。让每个兵自己判断"我要不要动"
   * 是微观决策，会互相顶死（我的更近是你、你的更近是我）。
   *
   * 链的读法：`岗位（末端） → … → 兵（源头）`。**从末端往源头排**，
   * 所以第一个动的是"已经贴着岗位的那个人"。
   */
  econOrder?: string[];
  /**
   * **战斗单位这一手走哪一格**（约束层一次排定）。
   *
   * 这不是"每格一个建议"，而是**一人一格、互不重复**的落点表：相邻两个人不会
   * 抢同一格，也就不会因为"谁先动"而互相堵死。用的是同一张距离场：
   * 起点是"目标城的可站格"，波穿过自己人（见 `constrain.planMarch`）。
   *
   * 打分层只负责执行；执行时如果这一格已经不可达（前面的人先动了），
   * 退回自己的走位（`stepToward`），不要硬报。
   */
  steps?: Record<string, { x: number; y: number }>;
  /**
   * 战斗单位这一手的**行动顺序**：离自己终点近的在前。
   *
   * 为什么顺序也要约束层给：30 个人挤成一团时，只有前排先挪开，后排的落点才空出来。
   * 按单位建立顺序派动作的话，后排常常先执行、把前排要去的格占了，前排就不动了——
   * 整队看上去在动（每手几十个 MOVE），实际原地踏步。
   */
  stepOrder?: string[];
  /**
   * 接管废墟：**派谁去、走到哪一格**。
   *
   * 单独给，不进 `squads`：队伍任务是"守/推"，而接管是"走进城格付钱"，
   * 后者不能被 `hold` 的"离城 2 格就停"截住（那正好停在他要进去的门口）。
   */
  captureId?: string;
  captureTarget?: { x: number; y: number };
  /**
   * 这一手**最多能花多少金**（采购上限）。
   *
   * 只在接管废墟的"攒钱/入驻"阶段出现：钱里要留出 `ruinCost` 那笔，
   * 不然会被一路造兵花光，走到废墟上又付不起（S-001 实测：248 金的重建费，
   * 全程金币 60~193，一次都没够过）。
   */
  spendCap?: number;
  /**
   * 采购门槛（2026-11-25 改，P2-2a）。
   *
   * `usable` = **对多数决目标"三发能解决"的兵种 id**（闸 1 的唯一口径）。
   * 由约束层用 `previewAttack` 算好，打分层只照着筛，不做判断。
   * 不在表里的兵种 = 打不动主要威胁 = 不造（宁可攒钱）。
   *
   * `survivable` = **穿过敌方射程时活不下来的排除**（闸 2）：
   * 暴露距离 = 敌射程 − 我射程，手数 = ceil(距离/我的移动力)，挨打 = 手数 × 敌方单发 × burst，
   * 挨打 ≥ 我的血就不该造——它在路上就没了，走不到能开火的位置。
   * 从城到战场那段不计（在敌方射程外，不挨打）。
   *
   * （原来的 `hp` 门槛——"血 > 对面最高单发"——已于 2026-11-25 P2-2b 删掉：
   * 它是"活得到"的粗糙版本，会把"射程够远、根本不挨打"的兵误杀。
   * 比如火枪 36 血 vs 步枪兵 36 攻，`>` 判死；但它射程 4、可以同格对射，实际一下都不挨。）
   *
   * `canPad` = 敌方**没有溅射/多段**，允许"买一堆打不动的便宜兵凑数"（以伤换伤）。
   * 敌方有一发清一片的能力时，充数是负资产，宁可攒钱。
   *
   * `range` 是**对面最大射程**。它决定的不是"门槛"，是"排序"：
   * 我方射程压不过它，就谈不上先手，这时候该比的是**血**（血薄的会被溅射一次清掉），
   * 不是射程。S-011 实测：造射程 3 的弓手去冲射程 5 的炮，弓手 22 血，一发就没。
   *
   * ── 2c 加的两个字段（2026-11-25，P2-2c）─────────────────────
   *
   * `bottleneck` = **这次采购真正被什么卡住**：
   *   · `'cell'`：守城。能站人的地方就是城的格子（2×2 只有 4 格），钱再多也放不下；
   *   · `'gold'`：其余（进攻/发展）。位置不受限，钱花完为止。
   * 它不改变任何门槛，只决定池内**按哪个数比**。
   *
   * `perCell` = **每格输出**（守城口径）：`我对多数决目标的伤害 × 它要挨几下才倒`。
   * 一份输出占一格，所以"每格"就是"这个兵种自己的总输出"，不除以价格。
   *
   * **为什么"每金"没有对应的比值**：P1 实测过——一旦拿价格做分母，就会选回 1 代民兵
   * （S-001 造 21 个、S-002 造 45 个，见 `V4-CODE-MAP` 9.17）。所以"钱是瓶颈"的时候
   * 的正确做法不是"每金最高"，而是**买得起的最强**（价格只在同分时做最后一档）。
   * 这条与 `DESIGN-PURCHASE-CRITERIA` 的表格有出入，以实测为准，记在 `V4-CODE-MAP` 9.19。
   */
  need?: {
    usable: string[];
    survivable: string[];
    range: number;
    canPad: boolean;
    /** 这次采购的瓶颈：守城 = `'cell'`（每格），其余 = `'gold'`（买得起的最强） */
    bottleneck: 'cell' | 'gold';
    /** 每格输出（只在 `bottleneck === 'cell'` 时用来排序）。缺某个兵种 = 没算（不该出现） */
    perCell: Record<string, number>;
  };
  /** 必须空出来的格子（产兵格、城门口）。打分层发现自家单位站着，第一件事就是把它挪开 */
  keepClear: number[];
  squads: Squad[];
  /**
   * 让位搬迁计划：`unitId → 这一手要挪到哪一格`。
   *
   * 为什么让位要有"计划"而不只是"判断"：关键格后面常常排着一串自己人
   * （产兵格被三个兵堵着、桥头后面跟着一队）。让一个人走开没用，整条链要一起挪一格。
   * 多源 BFS 从所有空格出发，给每个关键格配最近的"洞"，沿链倒推就得到每个单位的落点。
   *
   * 这一条**是约束**（必须做），不是打分——v3 把它和 `yieldPlan` 的分数混在一起，
   * 于是"让开"和"别送死"互相打折，最后谁也不让。
   */
  yieldMoves: Array<{ unitId: string; x: number; y: number }>;
  /**
   * **临时调令**（2026-11-25，清 9.18）：站在关键格上、但**本来有任务**的兵，这一手往哪走。
   *
   * 为什么需要它：`rest` 用"站在关键格上"把人从所有队伍里摘出去了（`constrain.ts:1189`），
   * 于是一个刚造出来、出生在产兵格上的兵**没有任何队**——`actFor` 走到
   * `if (!sq) return null`，只能开火、一步都不能走，直到敌人贴脸（那时城格不再是关键格）。
   *
   * 9.14 给了它一个任务名（`yield`），但落点是"最近的空格"——那是给产兵口服务的，
   * 方向常常是**往回**（过桥的兵被弹回西岸就是这么来的）。这里换成另一件事：
   * **朝它本来该去的那个目标走**（主队的目标 / 集结点 / 废墟）。
   *
   * 归队**不需要记状态**：编队每回合重建，它一离开关键格就自然回到 `rest` → 回主队。
   * 这就是"临时"两个字能成立的原因（v4 的编队本来就是无状态重算的）。
   *
   * 和 `yieldMoves` 的区别（两个都要，别合并）：
   *   · `yieldMoves` = 为了让**别人**用这一格（产兵口 / 出城通道），沿链倒推的搬迁；
   *   · `transit`    = 为了**它自己**回到任务上。两者方向经常相反。
   */
  transit?: Record<string, { x: number; y: number }>;
  /** 这一回合不许做的动作类型（比如"这回合不造经济兵"） */
  forbid?: string[];
  /**
   * **应急升级**（2026-11-25，P3 闸 A）：哪座城这一手该花钱升一级。
   *
   * 判据是"**翻不翻**"，不是"血和甲值多少钱"：按当前齐射城 ≤2 轮就塌、升完能多撑至少一轮、
   * 且剩下的钱还买得起一个打得穿又活得到的兵——三条全过才给。见 `planUpgrade`。
   *
   * 为什么不做"造兵 vs 升级"的比较：那要模拟两支队伍的交换（战力求解器的事）。
   * 这一层只保证"升级不会把造兵的路堵死"，谁先谁后由 `ai-v4` 的动作顺序定。
   */
  upgrade?: { cityId: string; cost: number; why: string; rounds: number };
  /**
   * **发展期 T**（2026-11-25，P3 闸 C 的 C1）：还要几回合才能威胁到对面城。
   *
   * 它是"经济发展到第几手"的期限——再晚出发，对面就升完本了（低代打高代）。
   *
   * 两种来源：
   *   · `squad`：有**进攻编队**（`main` 队、目标是敌城）时，全员到城下要几回合，
   *     速度取**队里最慢的那个兵**（快的等慢的）。
   *   · `map`：**没有进攻编队时**按地图算——双方非废墟城之间的最小步数 ÷ 当代战斗兵
   *     移动力的众数。为什么必须有这条：只有"有编队才有 T"会成死循环（T 不存在 →
   *     只发展不造兵 → 一直没有编队）。`expand` 的局面正是这个状态。
   *
   * C1/C2 只打印；C3 的求解器才开始读它。
   */
  horizon?:
    | { source: 'squad'; turns: number; squadId: string; cityId: string; n: number }
    | { source: 'map'; turns: number; fromCityId: string; cityId: string; move: number; steps: number };
}

/** 一个单位在本回合的归属：属于哪支队、任务是什么。查不到就是"没任务" */
export interface UnitTask {
  squadId: string;
  order: SquadOrder;
  at?: { x: number; y: number };
  cityId?: string;
}

/** `GameState.aiFocus[p].v4` 的形状（见 core/types.ts 里的同名注释） */
export interface V4Memory {
  /** 承诺：上一次做的决定、哪一手立的、管到第几手 */
  decision?: Decision & { since: number } | null;
  /** 事实：这支队第几手成立、当初定下打几个人（防止 want 每回合被人一死就缩） */
  squad?: { id: string; cityId: string; formedAt: number; want: number } | null;
  /**
   * 事实：每个经济兵是第几手造出来的（`unitId → 手数`）。
   *
   * 为什么需要记：岗位要按"谁先出生谁走远路"配（见 `constrain.planEconPosts`）。
   * 引擎的单位没有出生手数，只能自己记；只记事实，不记判断。
   */
  econSince?: Record<string, number>;
  /**
   * 事实：每个经济兵**出生在哪座城**（`unitId → cityId`）。
   *
   * 为什么不能每回合按"现在离哪座城近"算：人一走动，最近城就会翻，
   * 分组跟着翻 → 目标每回合重排 → 兵来回挪（实测长局里一整列都在原地打转）。
   * 出生城是事实，不会变。
   */
  econHome?: Record<string, string>;
}

/** 结构化日志的一条。出了问题先看它，别看代码 */
export interface DecisionLog {
  turn: number;
  decision: Decision | null;
  /** 每支队的规模和任务 */
  squads: Array<{ id: string; order: SquadOrder; n: number }>;
  /** 这回合为什么停手（null = 还有事可做） */
  idle?: string;
}
